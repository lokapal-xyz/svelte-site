	<h1>In dialogue</h1>
	<p class="lede">
		The treatise is self-contained. It still has to meet the literature it sits next to — without
		dissolving into it, and without walling itself off.
	</p>

	<div class="body">
		<p>Three different kinds of contact, not one uniform literature review:</p>
		<ul>
			<li>
				<strong>Political science</strong> takes the bulk of the work. Government systems is the applied
				niche; comparative government, institutionalism, and regime typologies are the home literature.
				The risk is overreach: EIC becoming political science with extra notation. A term earns its place
				here only if it lets us say something the field's own vocabulary does not already say as well.
			</li>
			<li>
				<strong>Philosophy</strong> is not imported. EIC's field association already is Philosophy. The
				work is to keep positioning EIC against the discipline it belongs to — already started in Attribute
				Position, which argues that EIC is narrower, and more disciplined, than mainstream Metaphysics.
			</li>
			<li>
				<strong>Systems theory</strong> stays light-touch on purpose. That is Systemics' own founding
				policy, not a deferral: concepts here are meant to coexist with other systems perspectives without
				forced consolidation.
			</li>
		</ul>
		<p>
			This section will grow as those contacts are written. It is not a substitute for the treatise.
		</p>
	</div>
</main>
